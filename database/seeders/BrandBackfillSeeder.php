    public function run()
    {
        DB::transaction(function () {
            $brandIds = [];

            foreach (self::PRODUCTS as $row) {
                if ($row['brand'] === null || isset($brandIds[$row['brand']])) {
                    continue;
                }

                $brand = Brand::firstOrCreate(
                    ['name' => $row['brand']],
                    ['is_active' => true]
                );

                $brandIds[$row['brand']] = $brand->id;
            }

            foreach (self::PRODUCTS as $id => $row) {
                $product = PasabuyProduct::find($id);

                if (! $product) {
                    continue;
                }

                $product->name = $row['name'];
                $product->brand_id = $row['brand'] !== null ? $brandIds[$row['brand']] : $product->brand_id;
                $product->save();
            }
        });

        $this->command?->info('Brand backfill complete: '.count(array_unique(array_filter(array_column(self::PRODUCTS, 'brand')))).' brands, '.count(self::PRODUCTS).' products updated.');
    }
